def _progress_by_status(statuses: tuple[str, ...]) -> Mapping[str, str]:
    total = len(statuses)
    return MappingProxyType(
        {status: f"{step}/{total}" for step, status in enumerate(statuses, start=1)},
    )


_DIPLOMA_PROGRESS: Final = _progress_by_status(_DIPLOMA_STATUSES)
_MASTER_PROGRESS: Final = _progress_by_status(_MASTER_STATUSES)


def diploma_progress(status: str) -> str:
    return _DIPLOMA_PROGRESS.get(status, f"0/{len(_DIPLOMA_STATUSES)}")


def master_progress(status: str) -> str:
    return _MASTER_PROGRESS.get(status, f"0/{len(_MASTER_STATUSES)}")
